import { generateHexDisk, hexEqual } from './hex-math';
import type { AxialCoord, LevelDefinition, MachineType } from './types';

function diskExcept(radius: number, excluded: AxialCoord[]): AxialCoord[] {
  return generateHexDisk(radius).filter(
    (c) => !excluded.some((ex) => hexEqual(c, ex)),
  );
}

